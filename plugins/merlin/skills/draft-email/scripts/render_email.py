#!/usr/bin/env python3
"""Build one email from a Markdown draft, the user's email template and their signature.

    python3 render_email.py DRAFT.md --about-me ABOUT_ME_FOLDER

DRAFT.md starts with a frontmatter block, then the body in Markdown:

    ---
    to: Jane Doe <jane@example.com>, sam@example.com
    cc: lee@example.com
    subject: The plan for Thursday
    ---
    Hi Jane,

    The body. **Bold**, *italic*, [a link](https://example.com), a bare https:// address,
    and lists written with "- " or "1. ".

`to` and `subject` are required. `cc` is optional. Each of to and cc is one line of
comma-separated addresses, or a list of "  - address" lines under the key.

The template is ABOUT_ME_FOLDER/email-template.html. When it is missing, the plugin's own
starter template is used and a line on standard error says so. A first HTML comment in the
template is its instructions and is left out of the email. What remains must hold exactly one
{{body}} slot and one {{signature}} slot. The signature is ABOUT_ME_FOLDER/email-signature.md,
when it exists: its lines are the sign-off, with headings and HTML comments left out.

Writes DRAFT.html (the HTML body) and DRAFT.txt (the plain-text body) beside the draft, and
nothing else. Prints one JSON object: to, cc, to_named, cc_named, subject, html, text, template,
used_starter. to and cc hold the bare addresses (jane@example.com), the form an email connector
takes. to_named and cc_named hold each entry as written in the draft, for showing the user.

Every draft is checked before anything is written. A refusal prints a plain reason on standard
error, writes nothing and exits 2. The output depends on the three inputs only, so running it
twice on the same files gives the same bytes. Standard library only.
"""

import argparse
import html
import json
import os
import re
import sys

TEMPLATE_NAME = 'email-template.html'
SIGNATURE_NAME = 'email-signature.md'
STARTER_REL = os.path.join('skeleton', 'HQ', 'context', 'ABOUT-ME', TEMPLATE_NAME)
SLOTS = ('{{body}}', '{{signature}}')
SLOT = re.compile(r'\{\{(body|signature)\}\}')
BUILD_MARKER = '<!-- Generated by the plugin build.'

P_STYLE = 'margin:0 0 16px 0;'
LIST_STYLE = 'margin:0 0 16px 0;padding-left:24px;'
LI_STYLE = 'margin:0 0 4px 0;'
SIG_STYLE = 'margin:0;'

# The standard Markdown rule: an emphasis run starts and ends with a non-space character, so
# "5 * 3 and 2 * 4" stays as typed and a lone asterisk is literal.
BOLD = re.compile(r'\*\*([^\s*][^*]*?[^\s*]|[^\s*])\*\*')
ITALIC = re.compile(r'\*([^\s*][^*]*?[^\s*]|[^\s*])\*')
# A Markdown link, or a bare web address. Emphasis never runs over a web address.
LINK = re.compile(r'\[([^\]]+)\]\(([^)\s]+)\)|(https?://[^\s<>()\[\]]+)')
GOOD_URL = re.compile(r'^(https?://[^\s/]+\S*|mailto:[^\s@]+@[^\s@]+)$', re.I)
ADDRESS = re.compile(r'^[^@\s<>",]+@[^@\s<>",]+\.[^@\s<>",]+$')
BULLET = re.compile(r'^\s*[-*]\s+(.*)$')
NUMBERED = re.compile(r'^\s*\d+[.)]\s+(.*)$')
TRAILING = '.,;:!?\'"'


class Refusal(Exception):
    pass


def esc(s):
    return html.escape(s, quote=False)


def attr(s):
    return html.escape(s, quote=True)


# ------------------------------------------------------------------ the draft

def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in '"\'':
        return v[1:-1].strip()
    return v


def parse_draft(path):
    with open(path, encoding='utf-8') as f:
        raw = f.read().replace('\r\n', '\n')
    m = re.match(r'^---\n(.*?)\n---[ \t]*(?:\n|$)(.*)$', raw, re.S)
    if not m:
        raise Refusal('The draft %s has no header lines at the top (the lines between --- and ---). It '
                      'must start with a line "---", then to:, subject: and cc: lines, then another "---". '
                      'Nothing was written.' % path)
    fm, list_key = {}, None
    for line in m.group(1).split('\n'):
        kv = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):(.*)$', line)
        if kv:
            key, val = kv.group(1).lower(), kv.group(2).strip()
            fm[key] = val
            list_key = key if not val else None
            continue
        item = re.match(r'^\s+-\s+(.*)$', line)
        if item and list_key:
            fm[list_key] = fm[list_key] + ',' + item.group(1) if fm[list_key] else item.group(1)
    return fm, m.group(2)


def split_addresses(value):
    """Split on commas outside quotes and angle brackets, so "Doe, Jane" <j@x.com> stays one."""
    out, cur, quote, angle = [], '', False, False
    for ch in value:
        if ch == '"' and not angle:
            quote = not quote
        elif ch == '<' and not quote:
            angle = True
        elif ch == '>' and not quote:
            angle = False
        if ch == ',' and not quote and not angle:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return [unquote(a) for a in out if unquote(a)]


def addresses(fm, key, required):
    """(bare, named): the bare addresses, and each entry as written, in the same order."""
    found = split_addresses(fm.get(key, ''))
    if required and not found:
        raise Refusal('The draft has no "%s:" line, or it is empty. Add who the email goes to, then build '
                      'it again. Nothing was written.' % key)
    bare = []
    for a in found:
        m = re.match(r'^(.*)<([^<>]*)>$', a)
        addr = (m.group(2) if m else a).strip()
        if not ADDRESS.match(addr):
            raise Refusal('"%s" in the "%s:" line is not an email address. Fix it, then build the email '
                          'again. Nothing was written.' % (a, key))
        bare.append(addr)
    return bare, found


# ------------------------------------------------------------------ the body

def emphasize(s):
    return ITALIC.sub(r'<em>\1</em>', BOLD.sub(r'<strong>\1</strong>', s))


def plain_emphasis(s):
    return ITALIC.sub(r'\1', BOLD.sub(r'\1', s))


def pieces(text):
    """[('prose', s) | ('link', label, url)] for one block of text, in order."""
    out, last = [], 0
    for m in LINK.finditer(text):
        if m.group(3):
            url = m.group(3).rstrip(TRAILING)
            if not url:
                continue
            start, end, label = m.start(), m.start() + len(url), None
        else:
            url, start, end, label = m.group(2), m.start(), m.end(), m.group(1)
            if not GOOD_URL.match(url):
                raise Refusal('The link "%s" goes to "%s", which is not a full web address. Write it in full, '
                              'starting with https:// (or mailto: for an email address), then build the email '
                              'again. Nothing was written.' % (label, url))
        if start < last:
            continue
        out.append(('prose', text[last:start]))
        out.append(('link', label, url))
        last = end
    out.append(('prose', text[last:]))
    return out


def inline_html(text):
    parts = []
    for p in pieces(text):
        if p[0] == 'prose':
            parts.append(emphasize(esc(p[1])))
        else:
            label = emphasize(esc(p[1])) if p[1] is not None else esc(p[2])
            parts.append('<a href="%s">%s</a>' % (attr(p[2]), label))
    return ''.join(parts)


def inline_text(text):
    parts = []
    for p in pieces(text):
        if p[0] == 'prose':
            parts.append(plain_emphasis(p[1]))
            continue
        label, url = p[1], p[2]
        shown = url[7:] if url.lower().startswith('mailto:') else url
        if label is None or plain_emphasis(label).strip() in (url, shown, re.sub(r'^https?://', '', url)):
            parts.append(shown)
        else:
            parts.append('%s (%s)' % (plain_emphasis(label), shown))
    return ''.join(parts)


def blocks(body):
    return [b.strip('\n') for b in re.split(r'\n[ \t]*\n', body.strip('\n')) if b.strip()]


def render_body(body):
    if '![' in body:
        raise Refusal('The draft has an image written as ![...](...). Images are not built into the email. '
                      'Remove that line, and add the image in your email app after the draft is there '
                      '(PNG, JPEG or GIF). Nothing was written.')
    html_out, text_out = [], []
    for b in blocks(body):
        lines = [ln.rstrip() for ln in b.split('\n')]
        for pattern, tag in ((BULLET, 'ul'), (NUMBERED, 'ol')):
            items = [pattern.match(ln) for ln in lines]
            if all(items):
                lis = ''.join('<li style="%s">%s</li>' % (LI_STYLE, inline_html(i.group(1))) for i in items)
                html_out.append('<%s style="%s">%s</%s>' % (tag, LIST_STYLE, lis, tag))
                if tag == 'ul':
                    text_out.append('\n'.join('- ' + inline_text(i.group(1)) for i in items))
                else:
                    text_out.append('\n'.join('%d. %s' % (n, inline_text(i.group(1))) for n, i in enumerate(items, 1)))
                break
        else:
            html_out.append('<p style="%s">%s</p>' % (P_STYLE, '<br>\n'.join(inline_html(ln.strip()) for ln in lines)))
            text_out.append('\n'.join(inline_text(ln.strip()) for ln in lines))
    if not html_out:
        raise Refusal('The draft has no body below its frontmatter. Write the email, then build it again. '
                      'Nothing was written.')
    return '\n'.join(html_out), '\n\n'.join(text_out)


# ------------------------------------------------------------------ signature and template

def render_signature(about_me):
    p = os.path.join(about_me, SIGNATURE_NAME)
    if not os.path.isfile(p):
        return '', ''
    with open(p, encoding='utf-8') as f:
        raw = f.read().replace('\r\n', '\n')
    raw = re.sub(r'<!--.*?-->', '', raw, flags=re.S)
    m = re.match(r'^---\n.*?\n---[ \t]*\n', raw, re.S)
    if m:
        raw = raw[m.end():]
    kept = '\n'.join(ln for ln in raw.split('\n') if not ln.lstrip().startswith('#'))
    html_parts, text_parts = [], []
    for b in blocks(kept):
        lines = [ln.strip() for ln in b.split('\n')]
        html_parts.append('<p style="%s">%s</p>' % (SIG_STYLE, '<br>\n'.join(inline_html(ln) for ln in lines)))
        text_parts.append('\n'.join(inline_text(ln) for ln in lines))
    return '\n'.join(html_parts), '\n\n'.join(text_parts)


def find_starter():
    d = os.path.dirname(os.path.abspath(__file__))
    while True:
        p = os.path.join(d, STARTER_REL)
        if os.path.isfile(p):
            return p
        nxt = os.path.dirname(d)
        if nxt == d:
            return None
        d = nxt


def load_template(about_me):
    own = os.path.join(about_me, TEMPLATE_NAME)
    used_starter = not os.path.isfile(own)
    path = find_starter() if used_starter else own
    if path is None:
        raise Refusal('There is no email template in %s, and the plugin\'s starter template is missing too. '
                      'Reinstall the plugin. Nothing was written.' % about_me)
    with open(path, encoding='utf-8') as f:
        text = f.read().replace('\r\n', '\n')
    text = '\n'.join(ln for ln in text.split('\n') if not ln.startswith(BUILD_MARKER))
    m = re.match(r'^\s*<!--.*?-->[ \t]*\n?', text, re.S)
    if m:
        text = text[m.end():]
    for slot in SLOTS:
        if text.count(slot) != 1:
            raise Refusal('The email template %s must hold %s exactly once, outside the note at the top of the '
                          'template. It holds '
                          'it %d times. Fix the template, then build the email again. Nothing was written.'
                          % (path, slot, text.count(slot)))
    return path, used_starter, text


# ------------------------------------------------------------------ main

def build(draft, about_me):
    if not draft.endswith('.md'):
        raise Refusal('The draft must be a .md file: %s. Nothing was written.' % draft)
    if not os.path.isfile(draft):
        raise Refusal('There is no draft at %s. Nothing was written.' % draft)
    if not os.path.isdir(about_me):
        raise Refusal('The about-me folder %s does not exist. Nothing was written.' % about_me)
    fm, body = parse_draft(draft)
    to, to_named = addresses(fm, 'to', True)
    cc, cc_named = addresses(fm, 'cc', False)
    subject = unquote(fm.get('subject', ''))
    if not subject:
        raise Refusal('The draft has no "subject:" line, or it is empty. Add a subject, then build it again. '
                      'Nothing was written.')
    body_html, body_text = render_body(body)
    sig_html, sig_text = render_signature(about_me)
    template, used_starter, shell = load_template(about_me)
    # One pass over the template only, so text from the draft or the signature is never scanned
    # for a slot: a body that says {{signature}} keeps it as typed.
    fill = {'body': body_html, 'signature': sig_html}
    out_html = SLOT.sub(lambda m: fill[m.group(1)], shell)
    out_text = body_text + ('\n\n' + sig_text if sig_text else '') + '\n'
    stem = draft[:-3]
    return {'to': to, 'cc': cc, 'to_named': to_named, 'cc_named': cc_named, 'subject': subject, 'html': stem + '.html', 'text': stem + '.txt',
            'template': template, 'used_starter': used_starter}, out_html, out_text


def main(argv=None):
    ap = argparse.ArgumentParser(description='Build one email from a Markdown draft.')
    ap.add_argument('draft')
    ap.add_argument('--about-me', required=True, help='the about-me folder that holds the template and signature')
    a = ap.parse_args(argv)
    draft = os.path.abspath(os.path.expanduser(a.draft))
    about_me = os.path.abspath(os.path.expanduser(a.about_me))
    try:
        env, out_html, out_text = build(draft, about_me)
    except Refusal as err:
        sys.stderr.write('draft-email: %s\n' % err)
        return 2
    except OSError as err:
        name = err.filename or 'one of the files'
        sys.stderr.write('draft-email: Merlin could not read %s (technical detail: %s). Nothing was written.\n'
                         % (name, err.strerror or err))
        return 2
    except UnicodeDecodeError as err:
        sys.stderr.write('draft-email: Merlin could not read one of the files, because it is not plain text '
                         '(technical detail: %s). Nothing was written.\n' % err)
        return 2
    with open(env['html'], 'w', encoding='utf-8', newline='\n') as f:
        f.write(out_html)
    with open(env['text'], 'w', encoding='utf-8', newline='\n') as f:
        f.write(out_text)
    if env['used_starter']:
        sys.stderr.write('draft-email: no email template in %s, so the plugin\'s starter template was used.\n'
                         % about_me)
    sys.stdout.write(json.dumps(env, ensure_ascii=False) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
