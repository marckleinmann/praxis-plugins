#!/usr/bin/env bash
# Merlin SessionStart hook (Claude Code and Codex).
#
# Prints one JSON line whose additionalContext is a short status header plus the
# rules digest (rules/digest.md). The business folder comes from the plugin
# option "Your business folder" when it is set, otherwise from the pointer file
# ~/.merlin/instance.json, which merlin:setup writes when the user chooses a folder
# in chat. A desktop-app install often cannot set the option at all, so the
# pointer is the normal source there.
#
#   - option set, folder exists and is writable: write the pointer when it is
#     missing or names a different folder; leave it byte for byte when it matches.
#   - folder missing, not a folder, or not writable: leave the pointer alone and
#     report read-only with the reason.
#   - option unset: never write; use the folder the pointer names, if any. With
#     no pointer either, no folder is chosen yet: that is not read-only, and the
#     status tells the user to run /merlin:setup.
#
# Only the hook may read plugin variables; skills and their scripts never get them.
# Honours a HOME override. Needs bash only: no python3, no node.

set -u

ROOT="${CLAUDE_PLUGIN_ROOT:-${PLUGIN_ROOT:-}}"
if [ -z "$ROOT" ]; then
  ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fi
OPTION="${CLAUDE_PLUGIN_OPTION_DATA_DIR:-}"
POINTER_DIR="${HOME}/.merlin"
POINTER="${POINTER_DIR}/instance.json"
BUILD_MARKER='<!-- Generated by the plugin build.'

# Read the event JSON up to its end, so the caller never blocks on a full pipe, but for two
# seconds at most, so a caller that never closes the pipe never holds the hook up. Only its "cwd"
# (the folder the session was opened on) is used, for the open-on line. With no input, no cwd in
# it, or a read that ran out of time, $PWD stands in; with neither, that line is left out.
INPUT=""
if [ ! -t 0 ]; then IFS= read -r -d '' -t 2 INPUT 2>/dev/null || true; fi

json_escape() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//$'\n'/\\n}
  s=${s//$'\r'/\\r}
  s=${s//$'\t'/\\t}
  printf '%s' "$s"
}

json_unescape() {
  local s=$1
  s=${s//\\\"/\"}
  s=${s//\\\//\/}
  s=${s//\\\\/\\}
  printf '%s' "$s"
}

expand_home() {
  case "$1" in
    "~") printf '%s' "$HOME" ;;
    "~/"*) printf '%s/%s' "$HOME" "${1#\~/}" ;;
    *) printf '%s' "$1" ;;
  esac
}

json_field() { # $1 JSON text, $2 key: prints that key's string value, or nothing
  # Reads pretty-printed and one-line JSON alike: a hand-written or compact pointer
  # must never read as "no folder".
  local raw val
  raw=$(printf '%s' "$1" | tr '\n\r' '  ')
  val=$(printf '%s' "$raw" | sed -nE 's/.*"'"$2"'"[[:space:]]*:[[:space:]]*"(([^"\\]|\\.)*)".*/\1/p')
  case "$val" in
    *'\u'*)
      # A \uXXXX escape (another tool's JSON writer): decode it with python3 when it is
      # there; without python3 the value is used as written.
      if command -v python3 >/dev/null 2>&1; then
        local dec
        if dec=$(python3 -c 'import json,sys; sys.stdout.write(json.loads("\"" + sys.argv[1] + "\""))' "$val" 2>/dev/null); then
          printf '%s' "$dec"; return 0
        fi
      fi ;;
  esac
  json_unescape "$val"
}

pointer_value() { # $1 key: prints the string value from the pointer, or nothing
  [ -f "$POINTER" ] || return 0
  local raw
  raw=$(cat "$POINTER" 2>/dev/null) || return 0
  json_field "$raw" "$1"
}

# The HQ rule: where Merlin's own files sit for a folder. The same rule is written in setup.py
# and in the task engine's tasklists.py; the plugin's tests hold the three together with one
# fixture matrix, so a change here is a change in both of them.
#   1  the folder is an HQ: its manifest.yaml carries the marker. Business is its parent.
#   2  the folder holds exactly one HQ child. Business is the folder.
#   3  the older flat layout: a manifest.yaml without the marker. Business and HQ are the folder.
#   4  nothing: not set up.
#   ambiguous  two or more children carry the marker.
# The marker is a top-level line, matched on bytes (LC_ALL=C) after one trailing carriage return
# is stripped. A folder's name never counts. Hidden children are never looked at, because the
# glob below skips them.
has_hq_marker() { # $1 manifest path
  [ -f "$1" ] && [ -r "$1" ] || return 1
  local LC_ALL=C
  local re='^kind:[[:space:]]*["'"'"']?merlin-hq["'"'"']?[[:space:]]*(#.*)?$'
  local line
  while IFS= read -r line || [ -n "$line" ]; do
    line=${line%$'\r'}
    [[ $line =~ $re ]] && return 0
  done 2>/dev/null < "$1"
  return 1
}

HQ_RULE=""; HQ_BIZ=""; HQ_DIR=""; HQ_CLASH=""
find_hq() { # $1 canonical folder: sets HQ_RULE, HQ_BIZ, HQ_DIR and HQ_CLASH
  local d=$1 c n count=0 first=""
  HQ_RULE=""; HQ_BIZ=$d; HQ_DIR=""; HQ_CLASH=""
  if has_hq_marker "$d/manifest.yaml"; then
    HQ_RULE=1; HQ_BIZ=$(dirname "$d"); HQ_DIR=$d; return 0
  fi
  for c in "$d"/*; do
    [ -d "$c" ] || continue
    n=${c##*/}
    case "$n" in .*) continue ;; esac
    if has_hq_marker "$c/manifest.yaml"; then
      count=$((count + 1))
      [ -z "$first" ] && first=$c
      HQ_CLASH="${HQ_CLASH:+${HQ_CLASH}, }\"${n}\""
    fi
  done
  if [ "$count" -gt 1 ]; then HQ_RULE="ambiguous"; return 0; fi
  if [ "$count" -eq 1 ]; then HQ_RULE=2; HQ_DIR=$first; HQ_CLASH=""; return 0; fi
  HQ_CLASH=""
  if [ -f "$d/manifest.yaml" ]; then HQ_RULE=3; HQ_DIR=$d; else HQ_RULE=4; fi
  return 0
}

# A move into an HQ folder that did not finish (merlin:setup's move step). Its record sits in the
# run-state folder it was written to: the flat one before that folder moves, the HQ's after. The
# places checked are the ones setup.py checks: the folder's own run-state folders, flat and HQ, and
# the HQ run-state folder of every child that is not hidden. A record whose status is not
# "complete" counts as unfinished, an unreadable one too.
MOVE_REC=""
move_unfinished() { # $1 record path
  [ -f "$1" ] || return 1
  local raw
  raw=$(cat "$1" 2>/dev/null) || return 0
  [ "$(json_field "$raw" status)" != "complete" ]
}
find_move() { # $1 canonical folder: sets MOVE_REC to the first unfinished record, or ""
  local c rel="state/merlin-setup/move-to-hq.json"
  MOVE_REC=""
  for c in "$1/$rel" "$1/live/$rel"; do
    if move_unfinished "$c"; then MOVE_REC=$c; return 0; fi
  done
  for c in "$1"/*; do
    [ -d "$c" ] || continue
    case "${c##*/}" in .*) continue ;; esac
    if move_unfinished "$c/live/$rel"; then MOVE_REC="$c/live/$rel"; return 0; fi
  done
  return 0
}

VERSION=$(sed -n 's/^[[:space:]]*"version":[[:space:]]*"\([^"]*\)".*/\1/p' "$ROOT/.claude-plugin/plugin.json" 2>/dev/null | head -n1)
[ -n "$VERSION" ] || VERSION="unknown"

DATA=""
SOURCE=""
if [ -n "$OPTION" ]; then
  DATA=$(expand_home "$OPTION")
  SOURCE="option"
else
  DATA=$(pointer_value data_root)
  [ -n "$DATA" ] && SOURCE="pointer"
fi

STATE=""
REASON=""
POINTER_NOTE=""
if [ -z "$DATA" ]; then
  STATE="unset"
elif [ "${DATA#/}" = "$DATA" ]; then
  STATE="readonly"; REASON="the folder setting is not a full path (it should start with /)"
elif [ ! -e "$DATA" ]; then
  STATE="readonly"; REASON="the folder does not exist (moved, renamed, or a drive that is not connected)"
elif [ ! -d "$DATA" ]; then
  STATE="readonly"; REASON="that path is a file, not a folder"
elif [ ! -w "$DATA" ] || [ ! -x "$DATA" ]; then
  STATE="readonly"; REASON="this computer account cannot write to that folder"
else
  CANON=$(cd "$DATA" 2>/dev/null && pwd -P)
  [ -n "$CANON" ] && DATA="$CANON"
  find_hq "$DATA"
  find_move "$DATA"
  case "$HQ_RULE" in
    1|2|3) STATE="ready" ;;
    ambiguous)
      STATE="readonly"
      REASON="the folder holds more than one HQ folder (${HQ_CLASH}), the folder where Merlin keeps its own files. Each one is marked as Merlin's HQ in its settings file (manifest.yaml), so Merlin cannot tell which one to use. Keep one and move the others out of the business folder: renaming one does not help, and a backup copy belongs outside the business folder" ;;
    *) STATE="notsetup" ;;
  esac
  if [ -n "$MOVE_REC" ]; then
    STATE="readonly"
    REASON="moving Merlin's own files into its HQ folder (the folder where Merlin keeps its own files) stopped before it finished. Nothing was deleted. The record of what moved and what did not is ${MOVE_REC}. Ask the user to run merlin:setup's move step again, which picks up where it stopped, or to ask for help"
  fi
fi

# Pointer: written only from the plugin option, only for a reachable folder.
if [ "$SOURCE" = "option" ] && { [ "$STATE" = "ready" ] || [ "$STATE" = "notsetup" ]; }; then
  CURRENT=$(pointer_value data_root)
  if [ -f "$POINTER" ] && [ "$CURRENT" = "$DATA" ]; then
    POINTER_NOTE="The pointer file ~/.merlin/instance.json already names this folder."
  else
    if mkdir -p "$POINTER_DIR" 2>/dev/null; then
      TMP="${POINTER_DIR}/.instance.json.$$"
      D=$(json_escape "$DATA")
      NOW=$(date -u +%Y-%m-%dT%H:%M:%SZ)
      if printf '{\n  "data_root": "%s",\n  "praxis_root": "%s",\n  "written_by": "merlin plugin %s, session-start hook",\n  "written_at": "%s",\n  "data_access": "local"\n}\n' \
          "$D" "$D" "$VERSION" "$NOW" > "$TMP" 2>/dev/null && mv -f "$TMP" "$POINTER" 2>/dev/null; then
        POINTER_NOTE="The pointer file ~/.merlin/instance.json was written now and names this folder."
      else
        rm -f "$TMP" 2>/dev/null
        POINTER_NOTE="The pointer file ~/.merlin/instance.json could not be written. Scripts and Codex will not find this folder until it can be."
      fi
    else
      POINTER_NOTE="The folder ~/.merlin could not be created, so the pointer file was not written. Scripts and Codex will not find the business folder until it can be."
    fi
  fi
elif [ "$SOURCE" = "pointer" ]; then
  POINTER_NOTE="This folder comes from the pointer file ~/.merlin/instance.json."
  if [ "$STATE" = "readonly" ] && [ "$HQ_RULE" != "ambiguous" ] && [ -z "$MOVE_REC" ]; then
    POINTER_NOTE="${POINTER_NOTE} If the folder was moved or renamed on purpose, merlin:setup can record the new one after the user's yes."
  fi
elif [ "$STATE" = "readonly" ]; then
  POINTER_NOTE="The pointer file ~/.merlin/instance.json was left as it was."
fi

# Where Merlin's own files sit inside the HQ folder, by layout. setup.py --where prints the same
# paths in full; the plugin's tests hold the two together.
FILES=""
if [ "$STATE" = "ready" ]; then
  if [ "$HQ_RULE" = 3 ]; then
    FILES="Merlin's files inside the HQ folder: notes about you (about-me) ABOUT-ME/, company notes (memory) memory/, task list TASKS.md, settings file (manifest) manifest.yaml, Merlin's working notes (run state) state/."
  else
    FILES="Merlin's files inside the HQ folder: notes about you (about-me) context/ABOUT-ME/, company notes (memory) context/memory/, task list live/TASKS.md, settings file (manifest) manifest.yaml, Merlin's working notes (run state) live/state/."
  fi
fi

# The open-on line: which part of the business folder this session was opened on. Both sides are
# canonical (pwd -P), so a symlinked Dropbox path compares correctly.
OPEN_ON=""
if [ "$STATE" = "ready" ]; then
  CWD_RAW=$(json_field "$INPUT" cwd)
  [ -n "$CWD_RAW" ] || CWD_RAW="${PWD:-}"
  CWD_CANON=""
  [ -n "$CWD_RAW" ] && CWD_CANON=$(cd "$CWD_RAW" 2>/dev/null && pwd -P)
  HQ_CANON=$(cd "$HQ_DIR" 2>/dev/null && pwd -P)
  if [ -n "$CWD_CANON" ]; then
    if [ "$HQ_RULE" != 3 ] && [ -n "$HQ_CANON" ] && { [ "$CWD_CANON" = "$HQ_CANON" ] || [ "${CWD_CANON#"$HQ_CANON"/}" != "$CWD_CANON" ]; }; then
      OPEN_ON="Open on: Merlin's HQ folder."
    elif [ "$CWD_CANON" = "$HQ_BIZ" ]; then
      OPEN_ON="Open on: the business folder itself."
    elif [ "${CWD_CANON#"$HQ_BIZ"/}" != "$CWD_CANON" ]; then
      SEG=${CWD_CANON#"$HQ_BIZ"/}
      SEG=${SEG%%/*}
      if [ "$HQ_RULE" != 3 ] && [ "$HQ_BIZ/$SEG" = "$HQ_DIR" ]; then
        OPEN_ON="Open on: Merlin's HQ folder."
      elif [ "$HQ_RULE" = 3 ] && case "$SEG" in ABOUT-ME|memory|state|.task-ids|.task-tmp) true ;; *) false ;; esac; then
        OPEN_ON="Open on: Merlin's own files."
      else
        OPEN_ON="Open on: project ${SEG}."
      fi
    else
      OPEN_ON="Open on: a folder outside the business folder."
    fi
  fi
fi

case "$STATE" in
  ready)
    case "$HQ_RULE" in
      3) WHERE="HQ folder: ${HQ_DIR}, the business folder itself: Merlin's own files sit loose in the business folder, the way older versions kept them." ;;
      1) WHERE="HQ folder: ${HQ_DIR}, which holds Merlin's own files. The folder setting names this HQ folder itself, and the business folder is the one around it." ;;
      *) WHERE="HQ folder: ${HQ_DIR}, which holds Merlin's own files." ;;
    esac
    STATUS="Status: ready. Business folder: ${HQ_BIZ}. ${WHERE} ${FILES} Setup has run. ${POINTER_NOTE}"
    [ -n "$OPEN_ON" ] && STATUS="${STATUS}
${OPEN_ON}" ;;
  notsetup)
    STATUS="Status: setup has not run. Business folder: ${DATA}. The folder exists but Merlin's settings file (manifest.yaml) is not in it yet. Before other Merlin work, tell the user once, in plain words, to run merlin:setup. ${POINTER_NOTE}" ;;
  readonly)
    STATUS="Status: read-only. Business folder: ${DATA}. Reason: ${REASON}. Merlin only reads this session and writes nothing anywhere until the folder is back. Tell the user which folder and what is wrong with it. ${POINTER_NOTE}" ;;
  *)
    STATUS="Status: no business folder chosen yet. This is not read-only. Before other Merlin work, tell the user once, in plain words, to run /merlin:setup: it asks which folder to use and records it after their yes. Until a folder is chosen, Merlin writes nothing except what merlin:setup writes after the user's yes. A folder merlin:setup records counts from then on, in this session too, with no new session needed. In Codex, merlin:setup records the folder the same way." ;;
esac

# The update line: the first start after Merlin's version changes on this computer asks the model to
# say so once in its first reply, because this start-up note is never shown to the user. The last
# version seen sits in ~/.merlin/last-version, beside the pointer. Only a recorded version that
# differs counts. With no record yet, the version in the pointer's written_by line stands in for it
# ("merlin plugin X, ..."; setup.py's WRITTEN_BY_RE reads the same line), because an install from
# before the record existed has none: a pointer written by another version says it once, and a
# first install, whose pointer this version wrote, says nothing. Either way the version is then
# recorded. Nothing is read or written while the folder is read-only or none is chosen, an unknown
# version never counts, and a failed write never stops the start-up.
UPDATE_LINE=""
LAST_VERSION="${POINTER_DIR}/last-version"
if [ "$VERSION" != "unknown" ] && { [ "$STATE" = "ready" ] || [ "$STATE" = "notsetup" ]; }; then
  LAST=""
  RECORD=0
  if [ -f "$LAST_VERSION" ]; then
    LAST=$(head -n1 "$LAST_VERSION" 2>/dev/null | tr -cd 'A-Za-z0-9.+_-' | cut -c1-64)
    [ "$LAST" != "$VERSION" ] && RECORD=1
  else
    RECORD=1
    LAST=$(pointer_value written_by 2>/dev/null | head -n1 | sed -n 's/^merlin plugin \([^[:space:],]\{1,\}\),.*/\1/p' 2>/dev/null | tr -cd 'A-Za-z0-9.+_-' | cut -c1-64)
    [ "$LAST" = "unknown" ] && LAST=""
  fi
  if [ -n "$LAST" ] && [ "$LAST" != "$VERSION" ]; then
    UPDATE_LINE="Update: Merlin was updated to version ${VERSION} since the last session on this computer. In your first reply, tell the user once, in one plain line, that Merlin was updated to version ${VERSION}. Do not say it again in this session."
  fi
  if [ "$RECORD" = 1 ]; then
    if mkdir -p "$POINTER_DIR" 2>/dev/null; then
      VTMP="${POINTER_DIR}/.last-version.$$"
      if ! { printf '%s\n' "$VERSION" > "$VTMP" && mv -f "$VTMP" "$LAST_VERSION"; } 2>/dev/null; then
        rm -f "$VTMP" 2>/dev/null
      fi
    fi
  fi
fi
[ -n "$UPDATE_LINE" ] && STATUS="${STATUS}
${UPDATE_LINE}"

DIGEST=""
if [ -f "$ROOT/rules/digest.md" ]; then
  DIGEST=$(grep -v -F "$BUILD_MARKER" "$ROOT/rules/digest.md")
else
  DIGEST="The Merlin rules digest is missing from the plugin folder (${ROOT}/rules/digest.md). Your business folder wins over any Claude memory. Run merlin:rules for the full rules."
fi

TEXT="# Merlin ${VERSION}
${STATUS}

${DIGEST}"

printf '{"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": "%s"}}\n' "$(json_escape "$TEXT")"
exit 0
